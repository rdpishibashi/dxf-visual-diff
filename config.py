"""
DXF Visual Diff - 設定ファイル

このファイルにはアプリケーション全体で使用される設定値が定義されています。
2026-09、Step「オプション設定」のUIをconfigファイルへ移行した際に新設した
（DXF-diff-manager の config.py と構造・コメント文言を揃えている）。
"""


class DiffConfig:
    """差分比較関連の設定"""

    # ── 差分抽出オプション ──

    # 色だけが異なる図形は変更なし扱いにする
    #   ※ この項目は utils/compare_dxf.py の ignore_color 対応が必要なため、
    #      DXF-diff-manager からの compare_dxf.py 移植が完了するまで未対応。
    #      設定しても効果がないため、あえて定義しない。
    # IGNORE_COLOR_ONLY_CHANGES = False

    # 差分検出の際の座標マージン
    #   同じ図形と判定する座標の許容誤差です。大きくするほど位置ずれを無視します。
    #   2026-09、DXF-diff-manager と揃えるため 0.01 → 0.05 に変更。
    DEFAULT_TOLERANCE = 0.05

    # レイヤー色設定（AutoCADカラーインデックス）
    #   1=赤 / 2=黄 / 3=緑 / 4=シアン / 5=青 / 6=マゼンタ / 7=白・黒 / 8=灰 / 9=明灰
    #
    #   2026-09-18、差分DXFを7レイヤー構成に変更。外部CADソフトでの閲覧を
    #   前提に、内容が同一のA_UNCHANGED/B_UNCHANGEDをUNCHANGED1枚へ統合し、
    #   代わりに合成レイヤーA_ALL/B_ALL（詳細カテゴリ層の物理複製）を新設した。
    #   「A_ALLを1枚ONにすればファイルAの全図形が色の区別つきで再現できる」
    #   「B_ALLを1枚ONにすればファイルBの全図形が色の区別つきで再現できる」
    #   ようにした。DXFの色はレイヤー属性ではなくエンティティ属性として
    #   各図形に直接書き込まれるため、1レイヤーに複数カテゴリが混在しても
    #   色による区別は失われない。
    DEFAULT_DELETED_COLOR = 6           # A_DELETED（削除図形。基準ファイルAのみに存在）
    DEFAULT_ADDED_COLOR = 4             # B_ADDED（追加図形。比較対象ファイルBのみに存在）
    DEFAULT_UNCHANGED_COLOR = 7         # UNCHANGED（変更なし図形。A/B共通1レイヤー）
    DEFAULT_UNCHANGED_OFFSET_A_COLOR = 8  # A_UNCHANGED_OFFSET（オフセット一致・A側旧位置。濃灰）
    DEFAULT_UNCHANGED_OFFSET_B_COLOR = 9  # B_UNCHANGED_OFFSET（オフセット一致・B側新位置。明灰）

    # ── オフセット補正の自動検出（2026-09-17新設。旧・手動設定UIは廃止）──
    #   ファイルA・Bで一致しなかった図形どうしを、位置に依存しない「形状」で
    #   対応付け、そのアンカー座標の差分（＝移動量）をオフセット候補として
    #   クラスタリングする。候補ごとに実際どれだけの図形が一致するかを検証し、
    #   下記のしきい値を満たしたものだけを UNCHANGED_OFFSET として採用する。
    #   複数のオフセットが同時に検出されうる（回路ブロックが複数箇所で
    #   別々に移動している場合など）。
    AUTO_OFFSET_DETECTION = True

    # 採用に必要な最小一致件数
    #   回路図の記号1個は複数エンティティ（線・円・文字等）で構成されるため、
    #   本物のブロック移動なら自然にこの規模になります。これ未満は「単独で
    #   動いた要素」とみなし、差分（DELETED+ADDED）のまま残します。
    #   （2026-09-17、下記「コンパクト救済」でより緩い条件による採用経路を追加）
    AUTO_OFFSET_MIN_MATCHES = 10

    # 採用に必要な最小形状種類数（偽陽性ガード）
    #   罫線や端子行のように同一形状が等間隔に並んでいると、1ピッチ分だけ
    #   ずらすと大量に「一致」してしまう偽陽性が起こります（一致件数だけでは
    #   本物の移動と区別できません）。一致した図形の形状の種類数がこの値
    #   以上あることも条件にすることで、単一形状の繰り返しパターンを除外します。
    AUTO_OFFSET_MIN_DISTINCT_SHAPES = 5

    # 採用するオフセットの最大個数（出力の複雑さに対する安全上限）
    #   2026-09-17、20→50に変更。コンパクト救済で採用候補が増えたことにより、
    #   一致件数の少ない救済分が上限に達して黙って切り落とされる事象が
    #   実データで発生したため（採用数は実測で28個程度に飽和し、50でも100でも
    #   結果は変わらない＝実際のフィルタは採用条件①②が担っている）。
    AUTO_OFFSET_MAX_OFFSETS = 50

    # 検証する候補オフセットの上限（得票数の多い順に上位N個のみ検証する）
    #   2026-09-17、50→100→200と2段階で変更。実データで「記号1個分の小さな移動」の
    #   候補が上位から漏れて検証対象にならない事例が複数見つかったため
    #   （50→100の変更後も、別の候補が122位に埋もれて漏れていた）。200では
    #   検出時間が約2倍になる（実データで03ペア3.1秒→6.3秒）反面、採用数が
    #   28→30個・一致件数が693→701件に増える。上限を上げるほど処理時間は
    #   線形に増える一方、救済できる候補は逓減していく（100→200の追加効果は
    #   300以降より小さい）ため、処理時間とのバランスでこの値にしている。
    AUTO_OFFSET_MAX_CANDIDATES = 200

    # 候補生成時、同一形状の出現数がこれを超える場合は対応付けが曖昧なため
    # 候補生成から除外する（組み合わせ爆発の防止も兼ねる）
    AUTO_OFFSET_MAX_INSTANCES_PER_SHAPE = 8

    # ── コンパクト救済（2026-09-17新設）──
    #   AUTO_OFFSET_MIN_MATCHES/MIN_DISTINCT_SHAPES の条件を満たさない場合でも、
    #   一致した図形が狭い範囲にまとまっていれば「記号1個が移動した」とみなして
    #   採用する、第2の採用経路です（どちらかの条件を満たせば採用）。
    #   実データ調査: 回路図の記号1個分の移動は一致した図形の広がり（バウンディング
    #   ボックスの対角長）が4〜15程度に収まるのに対し、無関係な偶然の一致は
    #   22〜48程度に散らばっていた。この違いを利用して、少数の一致でも
    #   「まとまって動いた」ものだけを救済する。

    # コンパクト救済の最小一致件数（AUTO_OFFSET_MIN_MATCHESより緩い値にする）
    AUTO_OFFSET_COMPACT_MIN_MATCHES = 4

    # コンパクト救済の最小形状種類数（AUTO_OFFSET_MIN_DISTINCT_SHAPESより緩い値にする）
    AUTO_OFFSET_COMPACT_MIN_DISTINCT_SHAPES = 2

    # コンパクト救済で許容する広がり（一致した図形のアンカー座標のバウンディング
    # ボックス対角長）の上限。これを超える場合は「散在した偶然の一致」とみなし
    # 不採用にする。
    AUTO_OFFSET_COMPACT_MAX_SPAN = 15.0


# 設定クラスのインスタンスを作成（簡単にアクセスできるように）
diff_config = DiffConfig()
